import type { ChunkDraft } from "./curriculumChunker.ts";

export interface SeedSource {
  title: string;
  sourceName: string;
  sourceUrl: string;
  subject: string;
  grade: string;
  track?: string;
  sourceYear?: number;
  docType: string;
  isOfficial: boolean;
  /** True only when a person compared the extracted text with the original official document. */
  verified: boolean;
  /** SHA-256 of the original file; makes re-running the seed a no-op. */
  sourceHash: string;
}

/** A SQL string literal. NUL bytes cannot be stored in Postgres text, so they are dropped. */
export function sqlString(value: string): string {
  return "'" + value.replaceAll("\0", "").replaceAll("'", "''") + "'";
}

/**
 * A dollar-quote tag that cannot be confused with the texts. The tag's opening part ("$c0", not
 * only "$c0$") must be absent too: a text ending in "$c0" would otherwise close the quote early.
 */
export function pickDollarTag(texts: string[]): string {
  for (let attempt = 0; ; attempt++) {
    const opening = "$c" + attempt;
    if (!texts.some((text) => text.includes(opening))) return opening + "$";
  }
}

/**
 * One idempotent statement that inserts a source and all its passages.
 * Running it twice does nothing the second time (the unique source_hash index).
 * Without verified = true the source is stored but invisible to search.
 */
export function buildSeedSql(source: SeedSource, chunks: ChunkDraft[]): string {
  const tag = pickDollarTag(chunks.map((chunk) => chunk.content));
  const verifiedAt = source.isOfficial && source.verified ? "now()" : "NULL";
  const values = chunks
    .map((chunk, index) => {
      const content = chunk.content.replaceAll("\0", "");
      const metadata = JSON.stringify(chunk.metadata).replaceAll("'", "''");
      return `  (${index}, ${tag}${content}${tag}, '${metadata}'::jsonb)`;
    })
    .join(",\n");

  return [
    "-- Generated by scripts/curriculum-ingest.ts. Review before running.",
    `-- Original file SHA-256: ${source.sourceHash}`,
    `-- Searchable by students: ${source.isOfficial && source.verified ? "YES" : "NO (not verified)"}`,
    "WITH new_source AS (",
    "  INSERT INTO public.curriculum_sources",
    "    (title, source_name, source_url, subject, grade, track, source_year, is_official, verified_at, doc_type, source_hash)",
    "  VALUES (",
    `    ${sqlString(source.title)}, ${sqlString(source.sourceName)}, ${sqlString(source.sourceUrl)},`,
    `    ${sqlString(source.subject)}, ${sqlString(source.grade)}, ${source.track ? sqlString(source.track) : "NULL"},`,
    `    ${source.sourceYear ?? "NULL"}, ${source.isOfficial}, ${verifiedAt}, ${sqlString(source.docType)}, ${sqlString(source.sourceHash)}`,
    "  )",
    "  ON CONFLICT (source_hash) WHERE source_hash IS NOT NULL DO NOTHING",
    "  RETURNING id",
    ")",
    "INSERT INTO public.curriculum_chunks (source_id, chunk_index, content, metadata)",
    "SELECT new_source.id, v.chunk_index, v.content, v.metadata",
    "FROM new_source",
    "CROSS JOIN (VALUES",
    values,
    ") AS v(chunk_index, content, metadata);",
    "",
  ].join("\n");
}

/** Statement that makes an already stored, unverified source searchable. Run it only after checking the text. */
export function buildVerifySql(sourceHash: string): string {
  return [
    "UPDATE public.curriculum_sources",
    "SET verified_at = now()",
    `WHERE source_hash = ${sqlString(sourceHash)} AND is_official = true;`,
    "",
  ].join("\n");
}
